def reframe(line: str) -> str:
    """A framed ASCII diagram line with the short name, padded to its old width."""
    new = FRAME_NAME.sub(ABBR, line)
    short = len(line) - len(new)
    start = FRAME_NAME.search(line)
    run = re.compile(r"( {2,}|─{2,})").search(new, start.start()) if start else None
    if short > 0 and run:
        new = new[: run.start()] + run.group(0)[0] * short + new[run.start() :]
    return new


